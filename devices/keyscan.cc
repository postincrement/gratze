uint8_t TRS80Emulator::ReadKeyboard(uint16_t addr)
{
  uint16_t mask = 1;
  uint8_t value = 0x00;
  for (int i = 0; i < 8; ++i) {
    if (addr & mask)
      value |= m_kbData[i];
    mask = mask << 1;
  }
  return value;
}